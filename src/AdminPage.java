    private void deletebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletebtnActionPerformed
        // TODO add your handling code here:
        
        try {
        // Check if a row is selected in the table
        int selectedRow = tbUsers.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(new JFrame(), "Please select a user from the table.", 
                                          "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Get the ID from the selected row
        String ID = tbUsers.getValueAt(selectedRow, 0).toString(); // Assuming ID is in column 0
        
        Class.forName("com.mysql.cj.jdbc.Driver");
        String url = "jdbc:mysql://localhost:3306/water";
        String user = "root";
        String pass = "";
        
        Connection con = DriverManager.getConnection(url, user, pass);
        String sql = "DELETE FROM user WHERE userID = ?";
        
        // Use PreparedStatement to execute the query
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, ID);
        int rowsAffected = pst.executeUpdate();
        
        if (rowsAffected > 0) {
            // Remove the row from the table model
            ((DefaultTableModel) tbUsers.getModel()).removeRow(selectedRow);
            JOptionPane.showMessageDialog(new JFrame(), "User deleted successfully.", 
                                          "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(new JFrame(), "Invalid ID.", 
                                          "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(new JFrame(), "Error: " + e.getMessage(), 
                                      "Error", JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_deletebtnActionPerformed

