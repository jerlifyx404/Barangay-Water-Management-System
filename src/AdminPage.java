    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
        // TODO add your handling code here:
        
        String ID = searchData.getText().trim();
        int notFound = 0;

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");

            String Url = "jdbc:mysql://localhost:3306/water";
            String User = "root";
            String Pass = "";

            Connection con = DriverManager.getConnection(Url, User, Pass);
            Statement st = con.createStatement();

            if (ID.isEmpty()) {
                JOptionPane.showMessageDialog(new JFrame(), "Search field is required", "Dialog",
                        JOptionPane.ERROR_MESSAGE);
            } else {
                // Dynamically build the SQL query
                String sql;
                if (ID.matches("\\d+")) { // Check if the input is numeric (likely an ID)
                    sql = "SELECT * FROM user WHERE userID = " + ID;
                } else {
                    sql = "SELECT * FROM user WHERE fullname LIKE '%" + ID + "%' OR username LIKE '%" + ID + "%'";
                }

                ResultSet rs = st.executeQuery(sql);

                if (rs.next()) {
                    // Create or access an instance of crudUser
                    crudUser crud = new crudUser();

                    // Use the getter methods to set the values in crudUser's text fields
                    crud.getFname().setText(rs.getString("fullname"));
                    crud.getEmailAddress().setText(rs.getString("email"));
                    crud.getUname().setText(rs.getString("username"));
//                    crud.getPass().setText(rs.getString("password"));
//                    crud.getConPass().setText(rs.getString("confirm_password"));

                    notFound = 1;

                    // Optionally, display the crudUser window if it isn't already visible
                    crud.setVisible(true);

                    con.close();
                }
                if (notFound == 0) {
                    JOptionPane.showMessageDialog(new JFrame(), "No matching record found", "Dialog",
                            JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (Exception e) {
            System.out.println("Error: " + e.getMessage());
        }
    }//GEN-LAST:event_searchActionPerformed

