    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        
                                          
    // Database connection details
    String url = "jdbc:MYSQL://localhost:3306/water";
    String user = "root";
    String pass = "";
    Connection con = null;

    try {
        // Establish the database connection
        con = DriverManager.getConnection(url, user, pass);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Database connection failed: " + e.getLocalizedMessage());
        return; // Exit the method if the connection fails
    }

    // Replace getUserID() with loginUser
    String loginUser = getUserID(); // Assuming this fetches the logged-in user's ID

    // SQL query to filter requests by userID
    String sql = "SELECT * FROM request WHERE userID = ?";
    try {
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, loginUser); // Use loginUser here
        ResultSet rs = pst.executeQuery();

        boolean recordsFound = false;

        while (rs.next()) {
            recordsFound = true;
            String userID = rs.getString("userID");
            String requestDate = rs.getString("request_date");
            String requestType = rs.getString("request_type");
            String notes = rs.getString("notes");
            String status = rs.getString("status");

            // Create and display a new RequestField frame
            AnnounceRequest AnnounceRequestFrame = new AnnounceRequest(userID, requestDate, requestType, notes, status);
            AnnounceRequestFrame.setVisible(true);
            AnnounceRequestFrame.pack();
            AnnounceRequestFrame.setLocationRelativeTo(null);
        }

        if (!recordsFound) {
            JOptionPane.showMessageDialog(null, "No requests found for userID: " + loginUser);
        }

        this.dispose(); // Dispose of the current frame
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error processing the request: " + e.getLocalizedMessage());
    } finally {
        try {
            if (con != null) {
                con.close(); // Close the connection
            }
        } catch (Exception e) {
            System.out.println("Error closing connection: " + e.getLocalizedMessage());
        }
    }

        
        
    }//GEN-LAST:event_jButton2ActionPerformed

