    private void resubmitbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_resubmitbtnActionPerformed

        
                                 
    
    // Get selected request type and notes from the UI
    String requestType = cbrequest.getText(); // Get selected request type
    String notes = renotes.getText(); // Get notes from text field

    // Ensure user selected a request type and entered notes
    if (requestType.isEmpty() || notes.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please select a request type and provide notes.");
        return;
    }

    // Validate userID to ensure it's not null or empty
    if (userID == null || userID.isEmpty()) {
        JOptionPane.showMessageDialog(null, "User ID is not set. Please log in.");
        return;
    }

    // Get the requested date from a text field (assuming 'dateInput' is the name of the field)
    String inputDate = redate.getText(); // e.g., "2020-12-01"

    // Validate if the input date is in correct format (YYYY-MM-DD)
    java.sql.Date requestDate = null;
    try {
        SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date parsedDate = dateFormat.parse(inputDate);
        requestDate = new java.sql.Date(parsedDate.getTime()); // Convert to SQL Date
    } catch (ParseException e) {
        JOptionPane.showMessageDialog(null, "Invalid date format. Please use YYYY-MM-DD.");
        return;
    }

    // Database connection details
    String Url = "jdbc:mysql://localhost:3306/water";
    String User = "root";
    String Pass = "";

    try {
        // Establish connection
        Connection con = DriverManager.getConnection(Url, User, Pass);
        String query = "INSERT INTO request (userID, request_date, request_type, notes, status) VALUES (?, ?, ?, ?, ?)";
        PreparedStatement stmt = con.prepareStatement(query);
        stmt.setString(1, userID);          // userID as a string
        stmt.setDate(2, requestDate);        // user-provided date
        stmt.setString(3, requestType);     // request type from user input
        stmt.setString(4, notes);           // Notes provided by the user
        stmt.setString(5, "Pending");       // Default status for the user

        // Execute the query
        stmt.executeUpdate();

        // Success message
        JOptionPane.showMessageDialog(null, "Request submitted successfully!");

    } catch (Exception e) { // Use Exception to catch all errors
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error submitting request: " + e.getMessage());
    }





        
    }//GEN-LAST:event_resubmitbtnActionPerformed

