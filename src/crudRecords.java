    private void submitbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitbtnActionPerformed
        // TODO add your handling code here:
        
     String Url = "jdbc:mysql://localhost:3306/water";  
    String User = "root";
    String Pass = "";

    // Input field variables
    String Date, Cubic, Balance, Amount, Remarks, UserID, TotalAmount;

    try {
        // Load the MySQL JDBC Driver
        Class.forName("com.mysql.cj.jdbc.Driver");
        Connection con = DriverManager.getConnection(Url, User, Pass);

        // Validation for empty fields
        if ("".equals(date.getText())) {
            JOptionPane.showMessageDialog(new JFrame(), "Date is required", "Error", JOptionPane.ERROR_MESSAGE);
        } else if ("".equals(cubic.getText())) {
            JOptionPane.showMessageDialog(new JFrame(), "Cubic is required", "Error", JOptionPane.ERROR_MESSAGE);
        } else if ("".equals(balance.getText())) {
            JOptionPane.showMessageDialog(new JFrame(), "Balance is required", "Error", JOptionPane.ERROR_MESSAGE);
        } else if ("".equals(remarks.getText())) {  // Changed from 'status' to 'remarks'
            JOptionPane.showMessageDialog(new JFrame(), "Remarks is required", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            // Retrieve input values
            Date = date.getText();
            Cubic = cubic.getText();
            Balance = balance.getText();
            Remarks = remarks.getText();

            // Calculate the Amount
            double cubicValue = Double.parseDouble(Cubic);
            double balanceValue = Double.parseDouble(Balance);
            double amountValue = cubicValue * 300.00; // Calculate the amount based on cubic input
            double totalAmountValue = amountValue + balanceValue; // Calculate totalAmount

            // Set the amount and totalAmount
            Amount = String.valueOf(amountValue);
            TotalAmount = String.valueOf(totalAmountValue);

            // **UserID Retrieval**
            // Replace this with how you retrieve the userID in your application
            UserID = userID;  // Example: Set userID to 1 for now (Ensure it exists in the related table)

            // Insert data into the database
            String query = "INSERT INTO record(date, cubic, amount, balance, total_amount, remarks, userID) " +
                           "VALUES(?, ?, ?, ?, ?, ?, ?)";

            PreparedStatement pstmt = con.prepareStatement(query);
            pstmt.setString(1, Date);
            pstmt.setInt(2, Integer.parseInt(Cubic));  // Assuming cubic is an integer
            pstmt.setDouble(3, amountValue);  // Balance is a decimal (Double)
            pstmt.setDouble(4, Double.parseDouble(Balance));  // Store the calculated amount
            pstmt.setDouble(5, totalAmountValue);  // Store the calculated totalAmount
            pstmt.setString(6, Remarks);
            pstmt.setString(7, UserID);

            pstmt.executeUpdate();

            // Reset the fields except for the calculated amount (optional)
            date.setText("");
            cubic.setText("");
            balance.setText("");
            remarks.setText("");  // Reset remarks field

            JOptionPane.showMessageDialog(null, "Successfully Recorded!");
        }
    } catch (NumberFormatException nfe) {
        JOptionPane.showMessageDialog(new JFrame(), "Invalid numeric input for Cubic or Balance", "Input Error", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        System.out.println("Error! " + e.getLocalizedMessage());
        JOptionPane.showMessageDialog(new JFrame(), "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }

        
    }//GEN-LAST:event_submitbtnActionPerformed

