    private void updateRecordsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateRecordsActionPerformed
        // TODO add your handling code here:
        
//     String userID = userIDField.getText();
//    String date = getDate().getText();
//    String cubic = getCubic().getText();
//    String balance = getBalance().getText();
//    String remarks = getRemarks().getText();
    
    
                                       
    // Input fields
    String Date = date.getText();
    String Cubic = cubic.getText();
    String Balance = balance.getText();
    String Remarks = remarks.getText();
    
    // Validate input
    if (Date.isEmpty() || Cubic.isEmpty() || Balance.isEmpty() || Remarks.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    try {
        // Parse numeric inputs
        double cubicValue = Double.parseDouble(Cubic);
        double balanceValue = Double.parseDouble(Balance);
        double amountValue = cubicValue * 300.00; // Calculate the amount based on cubic input
        double totalAmountValue = amountValue + balanceValue; // Calculate totalAmount

        // Set the calculated values
        String Amount = String.valueOf(amountValue);
        String TotalAmount = String.valueOf(totalAmountValue);

        // Perform the database update
        Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/water", "root", "");
        String sql = "UPDATE record SET date = ?, cubic = ?, amount = ?, balance = ?, total_amount = ?, remarks = ? WHERE recordID = ?";
        
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, Date);
        pst.setInt(2, Integer.parseInt(Cubic)); // Assuming cubic is an integer
        pst.setDouble(3, amountValue);
        pst.setDouble(4, balanceValue);
        pst.setDouble(5, totalAmountValue);
        pst.setString(6, Remarks);
        pst.setString(7, userID); // Use the userID passed from the context
        
        int rowsAffected = pst.executeUpdate();
        
        if (rowsAffected > 0) {
            JOptionPane.showMessageDialog(this, "Record updated successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
            // Reset fields after successful update
            date.setText("");
            cubic.setText("");
            balance.setText("");
            remarks.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update record", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException nfe) {
        JOptionPane.showMessageDialog(this, "Invalid numeric input for Cubic or Balance", "Input Error", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_updateRecordsActionPerformed

