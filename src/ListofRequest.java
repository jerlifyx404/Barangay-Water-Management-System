    private void viewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewActionPerformed
        // TODO add your handling code here:
 
                                    
   

    String Url = "jdbc:mysql://localhost:3306/water";
    String User = "root";
    String Pass = "";

    // Initialize the connection object
    Connection con = null;

    try {
        // Load the database driver and establish the connection
        Class.forName("com.mysql.cj.jdbc.Driver");
        con = DriverManager.getConnection(Url, User, Pass);

        // Prepare SQL query to select records based on userID
        String sql = "SELECT * FROM request WHERE userID = ?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, userID);  // Bind userID to the query

        // Execute the query
        ResultSet rs = pst.executeQuery();

        // Create or clear the table model before adding new data
        DefaultTableModel model = (DefaultTableModel) tbviewRequest.getModel();
        model.setRowCount(0); // Clear any existing rows

        // Add the fetched data to the table model
        while (rs.next()) {
            // Add each row of data to the table. Adjust the columns as needed.
            model.addRow(new Object[]{
                rs.getString("requestID"),
                rs.getString("request_date"),
                rs.getString("request_type"),
                rs.getString("notes"),
                rs.getString("status"),  // Fetch the current status
                rs.getString("userID"),
                
            });
        }
    } catch (Exception e) {
        // Handle errors
        System.out.println("Error: " + e.getLocalizedMessage());
    } finally {
        // Close the connection in the 'finally' block to ensure it gets closed even if an error occurs
        try {
            if (con != null && !con.isClosed()) {
                con.close();
            }
        } catch (Exception ex) {
            System.out.println("Error closing connection: " + ex.getLocalizedMessage());
        }
    }

    }//GEN-LAST:event_viewActionPerformed

