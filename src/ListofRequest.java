    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
           try {
        // Check if a row is selected in the table
        int selectedRow = tbviewRequest.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(new JFrame(), "Please select a Request from the table.", 
                                          "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Get the ID from the selected row
        String ID = tbviewRequest.getValueAt(selectedRow, 0).toString(); // Assuming ID is in column 0
        
        Class.forName("com.mysql.cj.jdbc.Driver");
        String Url = "jdbc:mysql://localhost:3306/water";
        String User = "root";
        String Pass = "";
        
        Connection con = DriverManager.getConnection(Url, User, Pass);
        String sql = "DELETE FROM request WHERE requestID = ?";
        
        // Use PreparedStatement to execute the query
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, ID);
        int rowsAffected = pst.executeUpdate();
        
        if (rowsAffected > 0) {
            // Remove the row from the table model
            ((DefaultTableModel) tbviewRequest.getModel()).removeRow(selectedRow);
            JOptionPane.showMessageDialog(new JFrame(), "Resquest deleted successfully.", 
                                          "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(new JFrame(), "Invalid ID.", 
                                          "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(new JFrame(), "Error: " + e.getMessage(), 
                                      "Error", JOptionPane.ERROR_MESSAGE);
    }
           
    }//GEN-LAST:event_jButton1ActionPerformed

